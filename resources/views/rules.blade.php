        <section id="match-structure" class="scroll-mt-28 border-t-2 border-base-content pt-8 grid lg:grid-cols-12 gap-8 lg:gap-14" data-aos="fade-up">
          <div class="lg:col-span-5 lg:sticky lg:top-28 self-start">
            <h2 class="font-heading text-3xl sm:text-4xl text-base-content">Match Structure</h2>
            <img src="/images/rulebook_illustrations/orange/header_match_structure.avif" alt="Match Structure" class="mt-6 w-full max-w-md h-auto ">
          </div>
          <div class="lg:col-span-7 divide-y divide-base-300">
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Overs and Deliveries</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">Each match consists of <span class="font-bold text-primary-ink">five overs</span>, with each over comprising <span class="font-bold text-primary-ink">four legal deliveries</span>.</p>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Team Size</h3>
              <ul class="mt-3 space-y-2 text-base-content/80 leading-relaxed">
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>Every team must have a squad of <span class="font-bold text-primary-ink">12 players</span> (9 male, 3 female).</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>The playing team will consist of <span class="font-bold text-primary-ink">8 players</span>.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>11 players can be chosen for one match, where any 8 can be active on the field at a time.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>Out of the 8 active players in any innings, at least 2 must be female.</span></li>
              </ul>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Player Substitution</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">The players chosen to bat and those chosen to bowl may be different, but once an innings begins, no changes to the selected players are allowed.</p>
            </div>
          </div>
        </section>

        <section id="first-over" class="scroll-mt-28 border-t-2 border-base-content pt-8 grid lg:grid-cols-12 gap-8 lg:gap-14" data-aos="fade-up">
          <div class="lg:col-span-5 lg:sticky lg:top-28 self-start">
            <h2 class="font-heading text-3xl sm:text-4xl text-base-content">First Over - Special Rules</h2>
            <img src="/images/rulebook_illustrations/orange/header_first_over.avif" alt="First Over" class="mt-6 w-full max-w-md h-auto ">
          </div>
          <div class="lg:col-span-7 divide-y divide-base-300">
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Female Players Only</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">The first over will be <span class="font-bold text-primary-ink">bowled exclusively by female players</span>, and <span class="font-bold text-primary-ink">only female players may bat</span> during this over.</p>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Wicket Limit</h3>
              <ul class="mt-3 space-y-2 text-base-content/80 leading-relaxed">
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>A maximum of <span class="font-bold text-primary-ink">two wickets</span> is allowed.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>If both wickets are lost, the innings will proceed directly to the next over, with any remaining deliveries declared dead.</span></li>
              </ul>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Runner Rule</h3>
              <ul class="mt-3 space-y-2 text-base-content/80 leading-relaxed">
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>If one female batter is dismissed, the other female batter will continue the remainder of the over, while the dismissed player will stand at the non-striker's end as a runner.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>In that case, a runout at either end will be counted as a dismissal.</span></li>
              </ul>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Wide/No-Ball Penalty</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">Each wide/no-ball delivery will award <span class="font-bold text-primary-ink">three runs</span> to the batting side <span class="font-bold text-primary-ink">without an extra delivery</span>.</p>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Fielding Restrictions</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">At least <span class="font-bold text-primary-ink">2 players must be positioned on the boundary line</span> during the first over.</p>
            </div>
          </div>
        </section>

        <section id="bowling" class="scroll-mt-28 border-t-2 border-base-content pt-8 grid lg:grid-cols-12 gap-8 lg:gap-14" data-aos="fade-up">
          <div class="lg:col-span-5 lg:sticky lg:top-28 self-start">
            <h2 class="font-heading text-3xl sm:text-4xl text-base-content">Bowling Rules</h2>
            <img src="/images/rulebook_illustrations/orange/header_bowling_rules.avif" alt="Bowling Rules" class="mt-6 w-full max-w-md h-auto ">
          </div>
          <div class="lg:col-span-7 divide-y divide-base-300">
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Bowling Limit</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">Each male player is permitted to bowl a <span class="font-bold text-primary-ink">maximum of one over</span> per match.</p>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Illegal Actions</h3>
              <ul class="mt-3 space-y-2 text-base-content/80 leading-relaxed">
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span><span class="font-bold text-primary-ink">Chucking is prohibited for male players</span>, and <span class="font-bold text-primary-ink">underarm bowling is prohibited for female players</span>.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>Any delivery deemed illegal by the umpire will be called a no-ball.</span></li>
              </ul>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">No-Ball Rules</h3>
              <ul class="mt-3 space-y-4">
                <li class="flex items-center gap-4">
                  <img src="/images/rulebook_illustrations/orange/no_ball_height.avif" alt="Height No-Ball" class="size-16 shrink-0 ">
                  <span class="text-base-content/80"><span class="font-semibold text-base-content">Over-height no-balls</span> judged at chest height. Bouncers are no-balls.</span>
                </li>
                <li class="flex items-center gap-4">
                  <img src="/images/rulebook_illustrations/orange/no_ball_foot.avif" alt="Foot No-Ball" class="size-16 shrink-0 ">
                  <span class="text-base-content/80"><span class="font-semibold text-base-content">Front-foot no-ball</span> called if foot lands beyond popping crease.</span>
                </li>
                <li class="flex gap-3 text-base-content/80 italic"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>No free hits will be awarded for no-balls</span></li>
              </ul>
            </div>
          </div>
        </section>

        <section id="fielding-wides" class="scroll-mt-28 border-t-2 border-base-content pt-8 grid lg:grid-cols-12 gap-8 lg:gap-14" data-aos="fade-up">
          <div class="lg:col-span-5 lg:sticky lg:top-28 self-start">
            <h2 class="font-heading text-3xl sm:text-4xl text-base-content">Fielding and Wide Rules</h2>
            <img src="/images/rulebook_illustrations/orange/header_fielding.avif" alt="Fielding Rules" class="mt-6 w-full max-w-md h-auto ">
          </div>
          <div class="lg:col-span-7 divide-y divide-base-300">
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Fielding Restrictions</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">A minimum of <span class="font-bold text-primary-ink">2 fielders must remain on each side of the pitch</span> at all times.</p>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Wide Ball Determination</h3>
              <ul class="mt-3 space-y-2 text-base-content/80 leading-relaxed">
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>For right-handed batters, the <span class="font-bold text-primary-ink">leg side relative to their stance will always be treated as wide</span>.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>For left-handed batters, the opposite applies.</span></li>
              </ul>
            </div>
            <div class="py-5">
              <h3 class="font-semibold text-lg text-base-content">Wide/Illegal Delivery Penalty (Overs 2-5)</h3>
              <p class="mt-2 text-base-content/80 leading-relaxed">In all overs except the first, each wide or illegal delivery will result in <span class="font-bold text-primary-ink">one run and an additional delivery</span>.</p>
            </div>
          </div>
        </section>

