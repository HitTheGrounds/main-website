              <ul class="mt-3 space-y-2 text-base-content/80 leading-relaxed">
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>If all male players are dismissed while female players still have not been dismissed, the remaining female players will be granted an additional opportunity to bat.</span></li>
                <li class="flex gap-3"><span class="mt-2.5 size-1.5 shrink-0 bg-primary"></span><span>In this case, they will face deliveries from any bowler (male or female) of the opposing team.</span></li>
